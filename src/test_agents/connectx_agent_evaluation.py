import numpy as np
import pandas as pd
import seaborn as sns
import matplotlib.pyplot as plt
from kaggle_environments import make, evaluate
from tqdm import tqdm
import os

# ==========================================
# 1. 설정 (Configuration)
# ==========================================
BASE_PATH = "/content/drive/MyDrive/25-2학기_강화학습기초_팀프로젝트/rl"  # 파일 경로
SEEDS = [0, 1, 2, 42, 999]       # 시드 목록
NUM_EPISODES = 10                # 대결당 게임 수 (연산량 고려하여 10으로 조정 추천, 필요시 20으로 변경)

# 평가 대상 에이전트 (My Agents)
my_agents = {
    "Greedy": "submission_simple_greedy_baseline.py",
    "Minimax": "submission_minimax_optimized_search.py",
    "MTD(f)": "submission_mtdf_negamax_strategic.py",
    "DQN": "submission_drl_double.py",
    "AlphaZero": "submission_alphazero_mcts_gap_defense.py"
}

# 상대방 풀 (Opponent Pool): Baseline + My Agents
# 모든 에이전트가 서로 한 번씩 붙습니다.
baselines = ["random", "negamax"]
opponent_pool = baselines + list(my_agents.keys())

# ==========================================
# 2. 리그전 실험 루프 (Round-Robin Tournament)
# ==========================================
match_results = []

print(f" 리그전 시작: {len(my_agents)}개 에이전트 vs {len(opponent_pool)}개 상대 x {len(SEEDS)}개 시드")
print(f"   (총 게임 수: {len(my_agents) * len(opponent_pool) * len(SEEDS) * NUM_EPISODES} 판 예상)\n")

# P1: 평가 대상 에이전트
for p1_name, p1_file in my_agents.items():
    p1_path = os.path.join(BASE_PATH, p1_file)

    if not os.path.exists(p1_path):
        print(f" 파일 없음: {p1_file} (건너뜀)")
        continue

    # P2: 상대방 에이전트
    for p2_name in opponent_pool:
        # 자기 자신과의 대결은 제외 (선택 사항)
        if p1_name == p2_name:
            continue

        # P2 에이전트 로드 (파일이면 경로, 문자열이면 그대로)
        if p2_name in my_agents:
            p2_agent = os.path.join(BASE_PATH, my_agents[p2_name])
        else:
            p2_agent = p2_name # "random" or "negamax"

        # 시드별 반복 실험
        # 진행바는 너무 많아지므로 간략하게 에이전트 단위로 표시하지 않음
        for seed in SEEDS:
            try:
                # evaluate 함수는 [P1, P2] 순서로 실행
                rewards = evaluate(
                    "connectx",
                    [p1_path, p2_agent],
                    num_episodes=NUM_EPISODES,
                    configuration={"randomSeed": seed}
                )

                # 승리 횟수 계산 (P1 기준)
                # 보상: [1, -1] (승), [-1, 1] (패), [0, 0] (무)
                wins = sum(1 for r in rewards if r[0] == 1)
                draws = sum(1 for r in rewards if r[0] == 0)
                losses = sum(1 for r in rewards if r[0] == -1)

                win_rate = wins / NUM_EPISODES

                match_results.append({
                    "Player": p1_name,
                    "Opponent": p2_name,
                    "Seed": str(seed),
                    "Win Rate": win_rate,
                    "Wins": wins,
                    "Losses": losses,
                    "Draws": draws
                })

            except Exception as e:
                print(f"Error: {p1_name} vs {p2_name} (Seed {seed}): {e}")

    print(f" Finished matches for {p1_name}")

# 데이터프레임 변환
df_matches = pd.DataFrame(match_results)

# ==========================================
# 3. 결과 분석 1: 종합 승률 (Overall Performance)
# ==========================================
# 각 에이전트가 '모든 상대'를 대상으로 거둔 평균 승률
overall_summary = df_matches.groupby("Player")["Win Rate"].agg(['mean', 'std', 'min', 'max'])
overall_summary.columns = ['Avg Win Rate (Total)', 'Std Dev', 'Min', 'Max']
overall_summary = overall_summary.sort_values(by="Avg Win Rate (Total)", ascending=False)

print("\n [종합 순위: 전체 상대 평균 승률]")
display(overall_summary)

# ==========================================
# 4. 결과 분석 2: 1:1 상대 전적 (Head-to-Head Matrix)
# ==========================================
# Pivot Table 생성 (행: Player, 열: Opponent, 값: Mean Win Rate)
h2h_matrix = df_matches.pivot_table(
    index="Player",
    columns="Opponent",
    values="Win Rate",
    aggfunc="mean"
)

# 컬럼 순서 정렬 (Baseline 먼저, 그 다음 점수 높은 순 등)
# 여기서는 Baseline을 앞쪽에 배치
sorted_cols = baselines + [c for c in h2h_matrix.columns if c not in baselines]
h2h_matrix = h2h_matrix[sorted_cols]

print("\n⚔️ [1:1 상대 전적 표 (평균 승률)]")
display(h2h_matrix.style.background_gradient(cmap="RdYlGn", axis=None).format("{:.2%}"))

# ==========================================
# 5. 결과 시각화: 히트맵 (Heatmap)
# ==========================================
plt.figure(figsize=(10, 8))
sns.heatmap(
    h2h_matrix,
    annot=True,
    fmt=".2f",
    cmap="RdYlGn",
    vmin=0,
    vmax=1,
    linewidths=.5,
    cbar_kws={'label': 'Win Rate'}
)
plt.title("Head-to-Head Win Rate Matrix (Averaged across Seeds)", fontsize=15, fontweight='bold')
plt.ylabel("Player (You)", fontsize=12)
plt.xlabel("Opponent", fontsize=12)
plt.show()

