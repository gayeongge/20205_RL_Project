# ==========================================
BASE_PATH = "/content/drive/MyDrive/25-2학기_강화학습기초_팀프로젝트/rl"  # 파일이 위치한 경로를 Google Drive 마운트 경로에 맞게 수정
SEEDS = [0, 1, 2, 42, 999]       # 검증할 시드 값 목록
NUM_EPISODES = 20                # 각 시드당 대결 횟수 (시간에 따라 조절 가능)
OPPONENT = "random"              # 대결 상대 (Baseline)

# 평가할 에이전트 파일 목록
agents_files = {
    "Greedy (1-step)": "submission_simple_greedy_baseline.py",
    "Minimax (N-step)": "submission_minimax_optimized_search.py", # 오타 수정됨
    "MTD(f) (Strategic)": "submission_mtdf_negamax_strategic.py",
    "Double DQN": "submission_drl_double.py",
    "AlphaZero (MCTS)": "submission_alphazero_mcts_gap_defense.py"
}

# ==========================================
# 2. 실험 루프 (Experiment Loop)
# ==========================================
results = []

print(f" 실험 시작: 총 {len(agents_files)}개 에이전트 x {len(SEEDS)}개 시드 테스트\n")

for agent_name, file_name in agents_files.items():
    file_path = os.path.join(BASE_PATH, file_name)

    # 파일 존재 여부 확인
    if not os.path.exists(file_path):
        print(f"⚠️ 파일 없음: {file_path} (건너뜀)")
        continue

    print(f"Evaluating {agent_name}...")

    for seed in tqdm(SEEDS, desc=f"Seeds for {agent_name}"):
        try:
            # 환경 설정 및 시드 고정
            # evaluate는 agent vs agent 대결 결과를 반환
            rewards = evaluate(
                "connectx",
                [file_path, OPPONENT],
                num_episodes=NUM_EPISODES,
                configuration={"randomSeed": seed}
            )

            # 승률 계산 (1: 승리, 0: 무승부/패배 - ConnectX evaluate 기준)
            # P1(내 에이전트)의 보상이 1이면 승리
            wins = sum(1 for r in rewards if r[0] == 1)
            win_rate = wins / NUM_EPISODES

            results.append({
                "Agent": agent_name,
                "Seed": str(seed), # 범주형 변환
                "Win Rate": win_rate
            })

        except Exception as e:
            print(f"Error on {agent_name} (Seed {seed}): {e}")

